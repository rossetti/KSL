package ksl.utilities.random.rvariable

import ksl.utilities.random.rng.RNStreamIfc
import ksl.utilities.random.rng.RNStreamProviderIfc

/**
 * Represents a multi-variate distribution with the specified marginals
 * The sampling of each marginal random variable is independent. That is the resulting
 * distribution has independent marginals. The supplied marginals may be the same
 * distribution or not.  If they are all the same, then use MVIndependentRV instead.
 * All the random variables will share the same stream. The sampling ensures that
 * is the sampling is consecutive within the stream and thus independent.
 *
 * The marginals draw from this variable's one stream, in turn, whatever its stream number, and so does every
 * marginal of its antithetic instance, whose stream is an antithetic copy of this one. Each marginal must
 * therefore be able to draw from a stream it is given (see [canShareStream]); the variable refuses one that cannot.
 * Antithetic pairs then correspond coordinate by coordinate when each marginal uses the same number of
 * pseudo-random numbers for every value, as variables generated by inverse transform do; a marginal generated by
 * acceptance-rejection can use a different number in the antithetic instance, which leaves the later coordinates
 * paired with other numbers: still correct samples, with less variance reduction.
 * @param marginals must have at least 2 supplied marginals, each able to share a stream
 * @param streamNum the random number stream number, defaults to 0, which means the next stream
 * @param streamProvider the provider of random number streams, defaults to [KSLRandom.DefaultRNStreamProvider]
 * @param name an optional name
 */
class MVIndependentMarginals @JvmOverloads constructor(
    marginals: List<RVariableIfc>,
    streamNum: Int = 0,
    streamProvider: RNStreamProviderIfc = KSLRandom.DefaultRNStreamProvider,
    name: String? = null
) : MVRVariable(streamNum, streamProvider, name) {

    private val myRVs: List<RVariable>

    init {
        require(marginals.size > 1) { "The number of supplied marginals must be at least 2" }
        require(marginals.all { it.canShareStream() }) {
            "Each marginal must be able to draw from this variable's stream (see canShareStream()); " +
                    "a marginal that is not an RVariable cannot"
        }
        // each marginal is built on this variable's stream number, which takes no further stream from the provider,
        // and then draws from this variable's one stream, in turn with the other marginals
        myRVs = marginals.map { (it.instance(streamNumber, streamProvider) as RVariable).also { m -> m.drawFrom(rnStream) } }
    }

    override fun drawFrom(stream: RNStreamIfc) {
        super.drawFrom(stream)
        for (rv in myRVs) {
            rv.drawFrom(stream)
        }
    }

    override val dimension: Int
        get() = myRVs.size

    override fun instance(streamNumber: Int, rnStreamProvider: RNStreamProviderIfc): MVIndependentMarginals {
        return MVIndependentMarginals(myRVs, streamNumber, rnStreamProvider)
    }

    override fun generate(array: DoubleArray) {
        require(array.size == dimension) { "The size of the array to fill does not match the sampling dimension!" }
        for ((i, rv) in myRVs.withIndex()) {
            array[i] = rv.sample()
        }
    }

}